use std::collections::BTreeMap;

fn context() -> Context {
    Context {
        slug: "mon_2695".into(),
        ports: BTreeMap::from([("frontend".into(), 24310u16), ("backend".into(), 24311u16)]),
        db_name: Some("mondrio_mon_2695".into()),
        main_worktree: "/home/carraes/mondrio/mondrio-platform".into(),
    }
}

fn set(pairs: &[(&str, &str)]) -> BTreeMap<String, String> {
    pairs
        .iter()
        .map(|(k, v)| (k.to_string(), v.to_string()))
        .collect()
}

#[test]
fn rewrites_a_key_in_place_and_leaves_its_neighbours_alone() {
    let source = "DEBUG=True\nVITE_API_URL=http://localhost:8000\nSENTRY_DSN=https://real\n";

    let out = render::env(
        source,
        &set(&[("VITE_API_URL", "http://localhost:{{ port.backend }}")]),
        &context(),
    )
    .expect("render");

    assert!(out.contains("VITE_API_URL=http://localhost:24311\n"));
    assert!(out.contains("DEBUG=True\n"));
    assert!(out.contains("SENTRY_DSN=https://real\n"));
    assert!(!out.contains("localhost:8000"));
}

#[test]
fn appends_a_key_the_source_never_had() {
    let source = "DEBUG=True\n";

    let out = render::env(
        source,
        &set(&[("MONGODB_DATABASE", "{{ db.name }}")]),
        &context(),
    )
    .expect("render");

    assert!(out.contains("MONGODB_DATABASE=mondrio_mon_2695\n"), "{out}");
    assert!(out.contains("DEBUG=True\n"));
}

/// The source is a human's real `.env.local`. Its comments and ordering are how they
/// navigate it, so a rewritten copy has to stay recognisable.
#[test]
fn keeps_comments_and_ordering() {
    let source = "# WorkOS -- ask the CTO for these\nWORKOS__API_KEY=sk_live\n\n# Database\nMONGODB_DATABASE=mondrio\n";

    let out = render::env(
        source,
        &set(&[("MONGODB_DATABASE", "{{ db.name }}")]),
        &context(),
    )
    .expect("render");

    // Past the two-line generated header, the file must read exactly as the source did.
    let body: Vec<&str> = out.lines().skip(2).collect();
    assert_eq!(
        body,
        [
            "# WorkOS -- ask the CTO for these",
            "WORKOS__API_KEY=sk_live",
            "",
            "# Database",
            "MONGODB_DATABASE=mondrio_mon_2695",
        ]
    );
}

/// A commented-out key is not the key. Rewriting it would leave the live value untouched
/// and the instance pointed at the wrong port, silently.
#[test]
fn a_commented_out_key_is_not_mistaken_for_the_real_one() {
    let source = "# VITE_API_URL=http://localhost:9999\nVITE_API_URL=http://localhost:8000\n";

    let out = render::env(
        source,
        &set(&[("VITE_API_URL", "http://localhost:{{ port.backend }}")]),
        &context(),
    )
    .expect("render");

    assert!(
        out.contains("# VITE_API_URL=http://localhost:9999\n"),
        "{out}"
    );
    assert!(
        out.contains("\nVITE_API_URL=http://localhost:24311\n"),
        "{out}"
    );
}

