/// A typo in a port name must not render an empty string into a URL, which would produce
/// `http://localhost:/` and a failure far from its cause.
#[test]
fn an_unknown_template_variable_is_an_error_not_an_empty_string() {
    let err = render::env(
        "",
        &set(&[("VITE_API_URL", "http://localhost:{{ port.backned }}")]),
        &context(),
    )
    .expect_err("must refuse an unknown port name");

    let msg = format!("{err:#}");
    assert!(
        msg.contains("backned"),
        "should name the bad reference: {msg}"
    );
}

const CONFIG: &str = r#"
version = 1

[ports]
names = ["backend"]

[[secrets]]
from = "backend/.env.local"
into = "backend/.env.local"

[secrets.set]
VITE_API_URL = "http://localhost:{{ port.backend }}"
"#;

/// The whole point: the worktree has no `.env.local`, the main checkout does, and the
/// agent has to do nothing about it.
#[test]
fn reads_from_the_main_checkout_and_writes_into_the_worktree() {
    let fx = Fixture::new();
    std::fs::create_dir_all(fx.main.join("backend")).expect("mkdir");
    std::fs::write(
        fx.main.join("backend/.env.local"),
        "WORKOS__API_KEY=sk_live\nVITE_API_URL=http://localhost:8000\n",
    )
    .expect("write main env");

    let wt = fx.add_worktree("mon_2695");
    assert!(
        !wt.join("backend/.env.local").exists(),
        "precondition: a fresh worktree carries no gitignored env"
    );
    let resolved = resolve::resolve(&wt).expect("resolve");
    let cfg = config::parse(CONFIG).expect("parse");

    let written = render::all(&cfg, &resolved, &context()).expect("render all");

    let body = std::fs::read_to_string(wt.join("backend/.env.local")).expect("read written");
    assert_eq!(written, [wt.join("backend/.env.local")]);
    assert!(
        body.contains("VITE_API_URL=http://localhost:24311"),
        "{body}"
    );
    assert!(
        body.contains("WORKOS__API_KEY=sk_live"),
        "secrets must come across untouched: {body}"
    );
    assert_eq!(
        std::fs::read_to_string(fx.main.join("backend/.env.local")).unwrap(),
        "WORKOS__API_KEY=sk_live\nVITE_API_URL=http://localhost:8000\n",
        "the main checkout's env must be untouched"
    );
}

#[test]
fn a_missing_source_names_the_main_checkout_it_looked_in() {
    let fx = Fixture::new();
    let wt = fx.add_worktree("mon_2695");
    let resolved = resolve::resolve(&wt).expect("resolve");
    let cfg = config::parse(CONFIG).expect("parse");

    let err = render::all(&cfg, &resolved, &context()).expect_err("must fail");

    let msg = format!("{err:#}");
    assert!(msg.contains("backend/.env.local"), "{msg}");
    assert!(
        msg.contains(&fx.main.display().to_string()),
        "should point at the main checkout, not this worktree: {msg}"
    );
}
